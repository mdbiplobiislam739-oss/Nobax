const TranslationContext = createContext<TranslationContextType | null>(null);

export function TranslationProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    return (localStorage.getItem('appLang') as Language) || 'English';
  });

  useEffect(() => {
    localStorage.setItem('appLang', language);
  }, [language]);

  const t = (key: string): string => {
    if (!key) return '';
    const trimmed = key.trim();

    // 1. Direct match in selected language
    if (translations[language]?.[key]) return translations[language][key];
    if (translations[language]?.[trimmed]) return translations[language][trimmed];

    // 2. Check if key is a known Bengali phrase that maps to an English key
    const mappedEnKey = bengaliToEnglishKeyMap[key] || bengaliToEnglishKeyMap[trimmed];
    if (mappedEnKey && translations[language]?.[mappedEnKey]) {
      return translations[language][mappedEnKey];
    }

    // 3. Reverse search through Bengali translations
    for (const [enKey, benVal] of Object.entries(translations.Bengali)) {
      if (benVal === key || benVal === trimmed) {
        if (translations[language]?.[enKey]) return translations[language][enKey];
      }
    }

    // 4. Reverse search through Hindi translations
    for (const [enKey, hinVal] of Object.entries(translations.Hindi)) {
      if (hinVal === key || hinVal === trimmed) {
        if (translations[language]?.[enKey]) return translations[language][enKey];
      }
    }

    // 5. If language is English, try finding by any translation
    if (language === 'English') {
      return mappedEnKey || key;
    }

    // Fallback
    return translations[language]?.[key] || key;
  };

  return (
    <TranslationContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </TranslationContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(TranslationContext);
  if (!context) throw new Error('useTranslation must be used within TranslationProvider');
  return context;
}
